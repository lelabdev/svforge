#!/usr/bin/env node
/**
 * Affected-scope resolver for PR CI (#570).
 *
 * Phase A of the issue's rollout: this module classifies a PR's changed files
 * into affected workspaces, tests and full-scope triggers, and REPORTS the
 * result. The existing CI pipeline still runs everything, so the resolver can
 * be validated in the open before any check is scoped.
 *
 * Rules (all deterministic, fixture-tested):
 * - a changed file under `packages/<dir>/` affects that workspace;
 * - affected workspaces pull in their TRANSITIVE REVERSE DEPENDENTS from the
 *   real workspace dependency graph (`workspace:*` / `@svforge/*` edges);
 * - an add-on change also affects `svforge` because its `module-recipes.ts`
 *   is extracted from the add-ons' real `run()` output;
 * - cross-cutting paths (lockfile, root configs, workflows, scripts, release
 *   tooling) are full scope;
 * - release metadata (`.changeset/**`, package `package.json`/`CHANGELOG.md`)
 *   is full scope: a `Version Packages` PR must never be treated as docs-only;
 * - documentation-only paths select no workspace/test;
 * - tests are owned by the workspaces their imports reference (derived, not
 *   guessed by a `packages/foo` glob over the whole file tree);
 * - an unknown path or a detector failure fails closed to full scope.
 *
 * Usage:
 *   node scripts/affected-scope.mjs --base <sha> [--head <sha>] [--json]
 *                                   [--summary <file>] [--json-out <file>]
 *                                   [--force-full] [--root <dir>]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

/** Root-level paths that always require the full suite. */
const GLOBAL_PREFIXES = [
	'scripts/',
	'tests/helpers/',
	'.github/',
	'docker/'
];
const GLOBAL_FILES = new Set([
	'bun.lock',
	'bun.lockb',
	'package.json',
	'tsconfig.json',
	'tsconfig.test-d.json',
	'vitest.config.ts',
	'eslint.config.js',
	'bunfig.toml',
	'.npmrc',
	'docker/'
]);

/** Release-sensitive metadata: a Version Packages PR must never be "docs-only". */
const RELEASE_METADATA_PREFIXES = ['.changeset/'];

/** Documentation-only paths: no workspace build or test is selected. */
const DOCS_PREFIXES = ['docs/'];

/** Generated artifacts with no build/test consumer (committed graph outputs). */
const ARTIFACT_PREFIXES = ['graphify-out/'];
const DOCS_FILES = new Set(['README.md', 'SECURITY.md', 'LICENSE', 'CONTRIBUTING.md']);

function toPosix(value) {
	return value.split('\\').join('/');
}

/** Read the workspace directories and their internal dependency edges. */
export function loadWorkspaces(root = process.cwd()) {
	const packagesDir = join(root, 'packages');
	const workspaces = [];
	for (const entry of readdirSync(packagesDir, { withFileTypes: true })) {
		if (!entry.isDirectory()) continue;
		const manifestPath = join(packagesDir, entry.name, 'package.json');
		if (!existsSync(manifestPath)) continue;
		const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
		const declared = { ...manifest.dependencies, ...manifest.devDependencies, ...manifest.peerDependencies };
		const dependencies = Object.entries(declared)
			.filter(([, range]) => String(range).startsWith('workspace:') || String(range).startsWith('@svforge/'))
			.map(([name]) => name);
		workspaces.push({
			dir: entry.name,
			name: manifest.name,
			prefix: `packages/${entry.name}/`,
			dependencies
		});
	}
	return workspaces.sort((a, b) => a.dir.localeCompare(b.dir));
}

/** Reverse dependency map, plus the add-on → svforge recipe extraction edge. */
export function reverseDependencies(workspaces) {
	const byName = new Map(workspaces.map((workspace) => [workspace.name, workspace]));
	const reverse = new Map(workspaces.map((workspace) => [workspace.name, new Set()]));
	for (const workspace of workspaces) {
		for (const dependency of workspace.dependencies) {
			reverse.get(dependency)?.add(workspace.name);
		}
	}
	// `packages/svforge/src/module-recipes.ts` is generated by running every
	// add-on's real run(), so an add-on change also affects the svforge build.
	if (byName.has('svforge')) {
		for (const workspace of workspaces) {
			if (workspace.name === 'svforge' || workspace.name === '@svforge/addon-kit') continue;
			reverse.get(workspace.name)?.add('svforge');
		}
	}
	return reverse;
}

/** Classify one changed path. Never guesses: unknown paths are full scope. */
export function classifyPath(path, workspaces) {
	const normalized = toPosix(path).replace(/^\.\//, '');
	if (normalized === '') return { kind: 'unknown', reason: 'empty path' };
	// Git never emits traversal segments; treat them as unrecognized (fail closed).
	if (normalized.split('/').includes('..')) {
		return { kind: 'unknown', reason: 'path traversal segment' };
	}
	if (GLOBAL_FILES.has(normalized) || GLOBAL_FILES.has(normalized.replace(/\/$/, ''))) {
		return { kind: 'global', reason: 'cross-cutting root configuration/tooling' };
	}
	for (const prefix of GLOBAL_PREFIXES) {
		if (normalized.startsWith(prefix)) return { kind: 'global', reason: `cross-cutting path (${prefix})` };
	}
	for (const prefix of RELEASE_METADATA_PREFIXES) {
		if (normalized.startsWith(prefix)) {
			return { kind: 'release-metadata', reason: 'release metadata (changesets)' };
		}
	}
	for (const prefix of DOCS_PREFIXES) {
		if (normalized.startsWith(prefix)) return { kind: 'docs', reason: `documentation (${prefix})` };
	}
	for (const prefix of ARTIFACT_PREFIXES) {
		if (normalized.startsWith(prefix)) return { kind: 'artifact', reason: `generated artifact (${prefix})` };
	}
	if (DOCS_FILES.has(normalized)) return { kind: 'docs', reason: 'documentation (root file)' };
	if (/^packages\/[^/]+\/(?:CHANGELOG\.md|package\.json)$/.test(normalized)) {
		return { kind: 'release-metadata', reason: 'release metadata (package version/changelog)' };
	}
	if (/^packages\/[^/]+\/docs\//.test(normalized) || /^packages\/[^/]+\/(?:README|AGENTS)\.md$/.test(normalized)) {
		return { kind: 'docs', reason: 'documentation (package)' };
	}
	if (/\.md$/.test(normalized) && !normalized.startsWith('packages/')) {
		return { kind: 'docs', reason: 'documentation (markdown)' };
	}
	if (normalized.startsWith('tests/')) return { kind: 'tests', reason: 'repository test suite' };
	for (const workspace of workspaces) {
		if (normalized === workspace.prefix.slice(0, -1) || normalized.startsWith(workspace.prefix)) {
			return { kind: 'workspace', workspace: workspace.name, reason: `owned by ${workspace.name}` };
		}
	}
	if (normalized.startsWith('packages/')) {
		return { kind: 'unknown', reason: 'path under packages/ but not a known workspace' };
	}
	return { kind: 'unknown', reason: 'unrecognized path' };
}

/** Derive test ownership from the imports each test file actually makes. */
export function deriveTestOwners(root, workspaces) {
	const testsDir = join(root, 'tests');
	const owners = new Map();
	if (!existsSync(testsDir)) return owners;
	const walk = (dir) => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else if (entry.name.endsWith('.test.ts')) {
				const relative = toPosix(full.slice(root.length + 1));
				const source = readFileSync(full, 'utf8');
				const owned = new Set();
				for (const workspace of workspaces) {
					const prefix = workspace.prefix;
					const bySourcePath =
						source.includes(`/${prefix}`) || source.includes(`'${prefix}`) || source.includes(`"${prefix}`);
					// Tests may also consume the built package by name (`import('svforge')`).
					const namePattern = new RegExp(
						`(?:from\\s+|import\\(|require\\()\\s*['"]${workspace.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]`
					);
					if (bySourcePath || namePattern.test(source)) owned.add(workspace.name);
				}
				owners.set(relative, owned);
			}
		}
	};
	walk(testsDir);
	return owners;
}

/** Files changed between the merge-base of `base` and `head`, and `head`. */
export function changedFiles({ root = process.cwd(), base, head = 'HEAD', git = execFileSync }) {
	const run = (args) => String(git('git', args, { cwd: root, encoding: 'utf8' })).trim();
	const mergeBase = run(['merge-base', base, head]);
	if (!mergeBase) throw new Error(`No merge-base between ${base} and ${head}.`);
	const output = run(['diff', '--name-status', '--find-renames', `${mergeBase}..${head}`]);
	return output
		.split('\n')
		.filter(Boolean)
		.map((line) => {
			const [status, ...paths] = line.split('\t');
			// A rename affects both the old and the new path.
			return { status: status[0], paths };
		});
}

/**
 * Build order for a set of packages: affected workspaces PLUS their forward
 * workspace dependencies, topologically sorted (dependencies first). Building a
 * package without its prerequisites would fail even though the package itself
 * did not change.
 */
export function buildOrderFor(affectedNames, workspaces) {
	const byName = new Map(workspaces.map((workspace) => [workspace.name, workspace]));
	const needed = new Set();
	const visit = (name) => {
		if (needed.has(name)) return;
		const workspace = byName.get(name);
		if (!workspace) return;
		needed.add(name);
		for (const dependency of workspace.dependencies) visit(dependency);
	};
	for (const name of affectedNames) visit(name);
	// Kahn-style topological sort restricted to `needed`; dependency edges only.
	const order = [];
	const placed = new Set();
	while (order.length < needed.size) {
		const ready = [...needed]
			.filter((name) => !placed.has(name))
			.filter((name) => (byName.get(name)?.dependencies ?? []).every((dep) => !needed.has(dep) || placed.has(dep)));
		if (ready.length === 0) throw new Error('Workspace dependency cycle detected.');
		for (const name of ready.sort()) {
			placed.add(name);
			order.push(name);
		}
	}
	return order.map((name) => ({ name, dir: byName.get(name)?.dir ?? '' }));
}

/**
 * Compute the affected scope. Pure apart from the injected test owners/workspaces.
 *
 * @returns {{
 *  global: boolean,
 *  mode: 'full'|'targeted'|'tests'|'none',
 *  reasons: Array<{path: string, kind: string, reason: string}>,
 *  packages: Array<{name: string, dir: string, reason: string}>,
 *  buildOrder: Array<{name: string, dir: string}>,
 *  tests: {mode: 'all'|'selected'|'none', files: string[]},
 *  docsOnly: boolean,
 *  releaseSensitive: boolean,
 *  fallback?: string
 * }}
 */
export function computeAffectedScope({ changes, workspaces, testOwners, forceFull = false }) {
	const reasons = [];
	const direct = new Set();
	let global = forceFull;
	let releaseSensitive = false;
	let docsOnly = changes.length > 0;
	const changedTests = new Set();
	if (forceFull) reasons.push({ path: '*', kind: 'forced', reason: '--force-full' });
	for (const change of changes) {
		for (const path of change.paths) {
			const classification = classifyPath(path, workspaces);
			reasons.push({ path, kind: classification.kind, reason: classification.reason });
			if (classification.kind === 'global' || classification.kind === 'unknown') global = true;
			if (classification.kind === 'release-metadata') {
				global = true;
				releaseSensitive = true;
			}
			if (classification.kind === 'workspace') direct.add(classification.workspace);
			if (classification.kind === 'tests') changedTests.add(toPosix(path));
			if (classification.kind !== 'docs' && classification.kind !== 'artifact') docsOnly = false;
		}
	}

	const names = new Map(workspaces.map((workspace) => [workspace.name, workspace]));
	const reverse = reverseDependencies(workspaces);
	const included = new Map();
	const addWithReason = (name, reason) => {
		if (included.has(name)) return;
		included.set(name, reason);
	};
	if (!global) {
		for (const name of direct) addWithReason(name, 'changed directly');
		let queue = [...direct];
		while (queue.length > 0) {
			const next = [];
			for (const name of queue) {
				for (const dependent of reverse.get(name) ?? []) {
					if (included.has(dependent)) continue;
					addWithReason(dependent, `depends on ${name}`);
					next.push(dependent);
				}
			}
			queue = next;
		}
	}
	const packages = global
		? workspaces.map((workspace) => ({ name: workspace.name, dir: workspace.dir, reason: 'full scope' }))
		: [...included].map(([name, reason]) => ({ name, dir: names.get(name)?.dir ?? '', reason }));

	let tests;
	if (global) {
		tests = { mode: 'all', files: [] };
	} else if (included.size > 0) {
		const selected = new Set(changedTests);
		for (const [file, owners] of testOwners) {
			if ([...owners].some((owner) => included.has(owner))) selected.add(file);
		}
		tests = { mode: 'selected', files: [...selected].sort() };
	} else if (changedTests.size > 0) {
		tests = { mode: 'selected', files: [...changedTests].sort() };
	} else {
		tests = { mode: 'none', files: [] };
	}

	const affectedNames = global ? workspaces.map((workspace) => workspace.name) : [...included.keys()];
	const buildOrder = global ? [] : buildOrderFor(affectedNames, workspaces);
	const mode = global
		? 'full'
		: included.size > 0
			? 'targeted'
			: tests.mode === 'selected'
				? 'tests'
				: 'none';
	return {
		global,
		mode,
		reasons,
		packages,
		buildOrder,
		tests,
		docsOnly,
		releaseSensitive
	};
}

/**
 * Conservative test-to-dist dependency model (#656).
 *
 * Repository tests do not only import sources: several of them inspect the
 * BUILT output of every workspace (`dist/index.js`, package entry points,
 * addon option registries loaded from `dist`, `npm pack` payloads, the CLI
 * binary). Scoping a build therefore has to know which artifacts a selected
 * test consumes; when that cannot be established, the only safe answer is a
 * full build. This model never skips a test — it escalates the build instead.
 */

/**
 * Patterns that reference built output in a way no static analysis can bound.
 * Only applied to files that already mention `dist`: returning "all" for a
 * bounded consumer costs a full build, never a skipped test.
 */
const UNBOUNDED_DIST_PATTERNS = [
	/readdirSync\(/,
	/packages\/\$\{/,
	/import\(`[^`]*\$\{/,
	/--filter\s+'?\*'?/,
	/npm\s+pack|bun\s+pack|pnpm\s+pack/,
	/bin\/svforge\.mjs/,
	/['"]packages['"]/,
	/\bPACKAGES\b/
];

/**
 * Built-artifact requirements of one source text.
 * @returns {{ kind: 'all'|'selected', workspaces: string[], reason: string }}
 */
export function distRequirementsForSource(source, workspaces) {
	const normalized = String(source ?? '');
	// `dist/`, `dist/index.js`, `distPath`, `'dist'`… count. A plain identifier
	// such as `readDist` does not: it names a helper, not built output.
	const mentionsDist = /dist(?:[/'"`.,)\s(]|Path|File|Dir|Entry|Output|Build)/.test(normalized);
	const importsBuiltName = workspaces.filter((workspace) => {
		const escaped = workspace.name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
		return new RegExp(`(?:from\\s+|import\\(|require\\()\\s*['"]${escaped}['"]`).test(normalized);
	});
	// #656 B-02: a NON-LITERAL dynamic import/require can load any compiled
	// package at runtime (`await import(packageName)`), so it is unbounded
	// BEFORE any "does this file mention dist?" shortcut. Detection must not
	// depend on the file also containing a literal dist reference.
	if (
		/\bimport\(\s*[^'"`)\s]/.test(normalized) ||
		/\bimport\(\s*`[^`]*\$\{/.test(normalized) ||
		/\brequire\(\s*[^'"`)\s]/.test(normalized)
	) {
		return {
			kind: 'all',
			workspaces: workspaces.map((workspace) => workspace.name),
			reason: 'dynamic import expression (unbounded)'
		};
	}
	// A subprocess that can install, build or invoke the CLI is equally
	// unbounded: it may require artifacts the static text never names.
	if (/(?:execFileSync|execSync|spawnSync|spawn|exec)\([\s\S]{0,300}(?:\bnpm\b|\bpnpm\b|\byarn\b|\bbun(?:x)?\b|svforge\.mjs|bin\/|--filter)/.test(normalized)) {
		return {
			kind: 'all',
			workspaces: workspaces.map((workspace) => workspace.name),
			reason: 'subprocess invocation (unbounded)'
		};
	}
	if (!mentionsDist && importsBuiltName.length === 0) {
		return { kind: 'selected', workspaces: [], reason: 'no built-artifact consumer' };
	}
	for (const pattern of UNBOUNDED_DIST_PATTERNS) {
		if (pattern.test(normalized)) {
			return {
				kind: 'all',
				workspaces: workspaces.map((workspace) => workspace.name),
				reason: 'unbounded dist consumer (dynamic enumeration / packaging)'
			};
		}
	}
	// A test that REFUSES to assert when a dist artifact is missing (a `return`
	// guard around `existsSync(...dist...)`) proves nothing when the build set
	// omitted that workspace: its requirement is uncertain → full build.
	if (/existsSync\([^)]*dist[^)]*\)[\s\S]{0,120}\breturn\b/.test(normalized)) {
		return {
			kind: 'all',
			workspaces: workspaces.map((workspace) => workspace.name),
			reason: 'conditional dist assertion (uncertain build requirement)'
		};
	}
	const required = new Set();
	if (mentionsDist) {
		for (const workspace of workspaces) {
			if (normalized.includes(workspace.prefix)) required.add(workspace.name);
		}
		// A `dist` reference that names no workspace is unbounded: fail closed.
		if (required.size === 0) {
			return {
				kind: 'all',
				workspaces: workspaces.map((workspace) => workspace.name),
				reason: 'dist reference without an identifiable workspace'
			};
		}
	}
	for (const workspace of importsBuiltName) required.add(workspace.name);
	return { kind: 'selected', workspaces: [...required].sort(), reason: 'bounded dist consumer' };
}

/** Extensions tried when a relative import omits one. */
// `.json` is data only (it cannot read built output) but resolving it avoids
// escalating a helper that imports a fixture catalog.
const IMPORT_EXTENSIONS = ['', '.ts', '.js', '.mjs', '.cjs', '.json', '/index.ts', '/index.js', '/index.mjs'];

/** Relative import/require/re-export specifiers of one source text. */
export function localImportSpecifiers(source) {
	const specifiers = new Set();
	const patterns = [
		// Statements may share a line (`import …; export … from …;`).
		/(?:^|[;\n])\s*(?:import|export)\s[^'"`;]*?from\s*['"]([^'"]+)['"]/g,
		/(?:^|[;\n])\s*import\s*['"]([^'"]+)['"]/g,
		/\bimport\(\s*['"]([^'"]+)['"]\s*\)/g,
		/\brequire\(\s*['"]([^'"]+)['"]\s*\)/g
	];
	for (const pattern of patterns) {
		for (const match of String(source ?? '').matchAll(pattern)) {
			if (match[1].startsWith('.')) specifiers.add(match[1]);
		}
	}
	return [...specifiers];
}

/** Resolve a relative import to a repository-relative file, or null. */
export function resolveLocalImport(root, fromFile, specifier) {
	const base = join(root, fromFile, '..', specifier);
	for (const extension of IMPORT_EXTENSIONS) {
		const candidate = `${base}${extension}`;
		if (existsSync(candidate) && statSync(candidate).isFile()) {
			const relative = toPosix(candidate.slice(root.length + 1));
			if (relative.startsWith('..')) return null;
			return relative;
		}
	}
	return null;
}

/**
 * Requirements of one repository file, including its LOCAL imports (#656 B-01).
 *
 * A test can look dist-free while a helper it imports reads built output, so the
 * analysis walks relative imports transitively for repository-owned helper code
 * (`tests/`, `scripts/`). Anything that cannot be proven bounded fails closed:
 * an unresolvable import, an unreadable file, a dynamic traversal, or a cycle
 * we cannot bound → full build. Files reached outside `tests/`+`scripts/`
 * (workspace sources imported by a test) are inspected once but not followed:
 * their internal imports are implementation of a source import, not built output.
 */
export function distRequirementsForFile(root, file, workspaces) {
	const fullScope = (reason) => ({
		kind: 'all',
		workspaces: workspaces.map((workspace) => workspace.name),
		reason
	});
	const visited = new Map();
	const analyse = (relativePath, follow) => {
		if (visited.has(relativePath)) return visited.get(relativePath);
		const result = { kind: 'selected', workspaces: [] };
		visited.set(relativePath, result);
		let source;
		try {
			source = readFileSync(join(root, relativePath), 'utf8');
		} catch {
			const failure = fullScope(`unreadable dist consumer (${relativePath})`);
			visited.set(relativePath, failure);
			return failure;
		}
		const own = distRequirementsForSource(source, workspaces);
		if (own.kind === 'all') {
			visited.set(relativePath, own);
			return own;
		}
		const required = new Set(own.workspaces);
		if (follow) {
			for (const specifier of localImportSpecifiers(source)) {
				const resolved = resolveLocalImport(root, relativePath, specifier);
				if (!resolved) {
					const failure = fullScope(`unresolvable local import '${specifier}' in ${relativePath}`);
					visited.set(relativePath, failure);
					return failure;
				}
				const repositoryOwned = /^(tests|scripts)\//.test(resolved);
				const nested = analyse(resolved, repositoryOwned);
				if (nested.kind === 'all') {
					visited.set(relativePath, nested);
					return nested;
				}
				for (const name of nested.workspaces) required.add(name);
			}
		}
		const bounded = { kind: 'selected', workspaces: [...required].sort(), reason: own.reason };
		visited.set(relativePath, bounded);
		return bounded;
	};
	return analyse(file, true);
}

/**
 * Every test file that consumes built artifacts, with its requirement.
 * Files with no built-artifact consumption are omitted.
 */
export function distInventory(root, workspaces) {
	const inventory = new Map();
	const walk = (dir) => {
		for (const entry of readdirSync(dir, { withFileTypes: true })) {
			const full = join(dir, entry.name);
			if (entry.isDirectory()) walk(full);
			else if (entry.name.endsWith('.test.ts')) {
				const relative = toPosix(full.slice(root.length + 1));
				const requirement = distRequirementsForFile(root, relative, workspaces);
				if (requirement.kind === 'all' || requirement.workspaces.length > 0) {
					inventory.set(relative, requirement);
				}
			}
		}
	};
	const testsDir = join(root, 'tests');
	if (existsSync(testsDir)) walk(testsDir);
	return inventory;
}

/**
 * Decide the build set for the selected tests.
 *
 * - every selected test's artifacts must be inside the scoped build order;
 * - an unbounded consumer, an unreadable file or a requirement outside the
 *   order escalates to a FULL build (tests are never skipped);
 * - otherwise the build stays scoped to the order computed for the change.
 */
export function planBuildSet({ root = process.cwd(), workspaces, buildOrder, testFiles }) {
	const orderDirs = buildOrder.map((entry) => entry.dir);
	const orderNames = new Set(buildOrder.map((entry) => entry.name));
	const escalate = (reason) => ({
		build: 'all',
		buildDirs: [],
		reason,
		requirements: [...orderNames]
	});
	const requirements = new Set();
	for (const file of testFiles) {
		const requirement = distRequirementsForFile(root, file, workspaces);
		if (requirement.kind === 'all') return escalate(`${file}: ${requirement.reason}`);
		for (const name of requirement.workspaces) requirements.add(name);
	}
	for (const name of requirements) {
		if (!orderNames.has(name)) return escalate(`test needs ${name}, outside the scoped build`);
	}
	return {
		build: orderDirs.length > 0 ? 'selected' : 'all',
		buildDirs: orderDirs,
		reason: requirements.size > 0 ? `scoped build covers ${[...requirements].sort().join(', ')}` : 'scoped build covers no dist consumer',
		requirements: [...requirements].sort()
	};
}

/** Fail closed: any detector failure becomes an explicit full-scope result. */
export function detectorFailureScope(error, workspaces) {
	return {
		global: true,
		fallback: error instanceof Error ? error.message : String(error),
		reasons: [{ path: '*', kind: 'detector-failure', reason: 'detector failure → full scope' }],
		mode: 'full',
		packages: workspaces.map((workspace) => ({ name: workspace.name, dir: workspace.dir, reason: 'full scope' })),
		buildOrder: [],
		tests: { mode: 'all', files: [] },
		docsOnly: false,
		releaseSensitive: false
	};
}

/** Human-readable explanation (also used as the GitHub step summary). */
export function formatScope(scope, { packageCount = scope.packages.length } = {}) {
	const lines = ['## Affected scope (report only)', ''];
	if (scope.fallback) lines.push(`> Detector failure → **full scope**: ${scope.fallback}`, '');
	if (scope.global) {
		lines.push('**Full scope** — every workspace, every test suite.');
		const triggers = scope.reasons.filter((reason) =>
			['global', 'unknown', 'release-metadata', 'forced', 'detector-failure'].includes(reason.kind)
		);
		for (const trigger of triggers.slice(0, 20)) lines.push(`- \`${trigger.path}\` — ${trigger.reason}`);
		if (triggers.length > 20) lines.push(`- …and ${triggers.length - 20} more trigger(s)`);
		return `${lines.join('\n')}\n`;
	}
	if (scope.docsOnly) {
		lines.push('**No build/test scope** — documentation/generated-artifact only.');
		return `${lines.join('\n')}\n`;
	}
	lines.push(`**Workspaces (${scope.packages.length}/${packageCount})**`);
	for (const pkg of scope.packages) lines.push(`- \`${pkg.name}\` — ${pkg.reason}`);
	lines.push('', `**Tests** — ${scope.tests.mode}${scope.tests.files.length ? ` (${scope.tests.files.length})` : ''}`);
	for (const file of scope.tests.files.slice(0, 40)) lines.push(`- \`${file}\``);
	if (scope.tests.files.length > 40) lines.push(`- …and ${scope.tests.files.length - 40} more`);
	return `${lines.join('\n')}\n`;
}

function parseArgs(argv) {
	const options = { head: 'HEAD', json: false, jsonOut: null, summary: null, forceFull: false, root: process.cwd() };
	for (let index = 0; index < argv.length; index++) {
		const arg = argv[index];
		if (arg === '--base') options.base = argv[++index];
		else if (arg === '--head') options.head = argv[++index];
		else if (arg === '--json') options.json = true;
		else if (arg === '--json-out') options.jsonOut = argv[++index];
		else if (arg === '--summary') options.summary = argv[++index];
		else if (arg === '--force-full') options.forceFull = true;
		else if (arg === '--root') options.root = argv[++index];
		else throw new Error(`Unknown argument: ${arg}`);
	}
	if (!options.base && !options.forceFull) throw new Error('Missing required --base <ref> (or --force-full).');
	return options;
}

export function runCli(argv = process.argv.slice(2)) {
	const options = parseArgs(argv);
	const workspaces = loadWorkspaces(options.root);
	let scope;
	try {
		const forceFull = options.forceFull || !options.base || process.env.FORCE_FULL === '1';
		const changes = forceFull ? [] : changedFiles({ root: options.root, base: options.base, head: options.head });
		const testOwners = deriveTestOwners(resolve(options.root), workspaces);
		scope = computeAffectedScope({ changes, workspaces, testOwners, forceFull });
	} catch (error) {
		scope = detectorFailureScope(error, workspaces);
		process.exitCode = 2;
	}
	const human = formatScope(scope);
	if (options.json) console.log(JSON.stringify(scope, null, 2));
	else console.log(human);
	if (options.jsonOut) writeFileSync(options.jsonOut, `${JSON.stringify(scope, null, 2)}\n`);
	if (options.summary) writeFileSync(options.summary, human, { flag: 'a' });
	return scope;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
	try {
		runCli();
	} catch (error) {
		console.error(`affected-scope: ${error instanceof Error ? error.message : error}`);
		process.exitCode = 2;
	}
}
